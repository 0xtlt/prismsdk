#!/usr/bin/env python3
"""Generates the WidgetKit entry point for an app's registered widgets.

    generate_widgets.py widgets.json ios|macos > Generated.swift

`widgets.json` comes from `PRISM_DESCRIBE=widgets <app>`. Each Prism widget
becomes a StaticConfiguration rendered by the generic PrismWidgetView; on iOS
the Live Activity configuration (lock screen + Dynamic Island) is added too.
"""
import json
import re
import sys

ACCESSORY = {"accessoryCircular", "accessoryRectangular", "accessoryInline"}

widgets = json.load(open(sys.argv[1]))
platform = sys.argv[2]

def swift_str(s):
    return json.dumps(s, ensure_ascii=False)

out = ["// Generated by platform/apple/generate_widgets.py. Do not edit.",
       "import SwiftUI", "import WidgetKit", ""]
names = []
for w in widgets:
    name = "PrismWidget_" + re.sub(r"\W", "_", w["kind"])
    names.append(name)
    families = [f for f in w["families"] if platform == "ios" or f not in ACCESSORY]
    if platform == "macos":
        families = [f for f in families if f != "systemExtraLarge"] or ["systemSmall"]
    fams = ", ".join("." + f for f in families) or ".systemSmall"
    out += [
        f"struct {name}: Widget {{",
        "    var body: some WidgetConfiguration {",
        f"        StaticConfiguration(kind: {swift_str(w['kind'])}, provider: PrismProvider(kind: {swift_str(w['kind'])})) {{ PrismWidgetView(entry: $0) }}",
        f"            .configurationDisplayName({swift_str(w['name'])})",
        f"            .description({swift_str(w['description'])})",
        f"            .supportedFamilies([{fams}])",
        "    }",
        "}",
        "",
    ]
out += ["@main", "struct PrismWidgetBundle: WidgetBundle {", "    var body: some Widget {"]
out += [f"        {n}()" for n in names]
if platform == "ios":
    out.append("        PrismLiveActivity()")
if not names and platform != "ios":
    out.append("        EmptyWidget()")
out += ["    }", "}"]
print("\n".join(out))
