#!/usr/bin/env python3
"""Generates crates/prism-core/src/apple_models.rs from the iOS Simulator device
profiles Xcode installs (model ids, marketing names, screens and their ppi).

    python3 scripts/apple-models.py && cargo fmt     # after installing a new Xcode

Real devices have no such profiles, so the table ships in the app.
"""
import glob, os, plistlib, sys

ROOT = "/Library/Developer/CoreSimulator/Profiles/DeviceTypes"
OUT = os.path.join(os.path.dirname(__file__), "..", "crates", "prism-core", "src", "apple_models.rs")

models = {}
for path in sorted(glob.glob(f"{ROOT}/*.simdevicetype")):
    name = os.path.basename(path).removesuffix(".simdevicetype")
    res = os.path.join(path, "Contents", "Resources")
    try:
        profile = plistlib.load(open(os.path.join(res, "profile.plist"), "rb"))
        caps = plistlib.load(open(os.path.join(res, "capabilities.plist"), "rb"))
    except OSError:
        continue
    if not set(profile.get("supportedProductFamilyIDs", [])) & {1, 2}:  # iPhone, iPad
        continue
    displays = caps.get("capabilities", caps).get("displays", [])
    screens = [(int(d["width"]), int(d["height"]), float(d.get("hdpi", 0))) for d in displays
               if d.get("displayType") == "integrated" and d.get("hdpi")]
    if not screens:
        continue
    ids = profile.get("representedModelIdentifiers") or [profile["modelIdentifier"]]
    # Memory variants ("(16GB)") share the model id: keep the plain name.
    name = name.replace(" (16GB)", "")
    for model_id in ids:
        models.setdefault(model_id, (name, screens))

if not models:
    sys.exit(f"no device profiles under {ROOT}")

def key(m):
    family, _, nums = m[0].partition(",")
    prefix = family.rstrip("0123456789")
    return (prefix, int(family[len(prefix):] or 0), int(nums or 0))

lines = [
    "//! Generated by `scripts/apple-models.py` from the iOS Simulator device",
    "//! profiles: do not edit by hand.",
    "",
    "/// (model id, marketing name, screens as (width px, height px, ppi)).",
    "/// Foldables list one entry per built-in display, in the profile's order.",
    "pub(crate) type Screens = &'static [(u32, u32, f32)];",
    "",
    "pub(crate) const MODELS: &[(&str, &str, Screens)] = &[",
]
for model_id, (name, screens) in sorted(models.items(), key=key):
    s = ", ".join(f"({w}, {h}, {ppi})" for w, h, ppi in screens)
    lines.append(f'    ("{model_id}", "{name}", &[{s}]),')
lines.append("];")
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"{len(models)} models → {os.path.normpath(OUT)}")
