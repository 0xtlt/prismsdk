#!/usr/bin/env python3
"""Generates the WidgetKit entry point for an app's registered widgets.

    generate_widgets.py widgets.json ios|visionos|macos > Generated.swift

`widgets.json` comes from `PRISM_DESCRIBE=widgets <app>`. Each Prism widget
becomes a StaticConfiguration rendered by the generic PrismWidgetView; on iOS
the Live Activity configuration (lock screen + Dynamic Island) is added too.
visionOS has neither lock-screen families nor Live Activities (no ActivityKit).

A widget with parameters (`Widget::parameter`) becomes an
AppIntentConfiguration instead (iOS 17, macOS 14): a WidgetConfigurationIntent
with one @Parameter per parameter, each an AppEntity whose EntityQuery lists
the options the app wrote to the App Group (PrismWidgetKit.swift reads them).
The types are spelled out per kind and parameter, with literal titles, so the
App Intents metadata processor can extract them at build time.

The parameters are not optional: WidgetKit fills a required entity parameter
with its query's `defaultResult()` when the widget is added, so the « Edit
widget » sheet shows the default option. An optional one starts empty, and
the sheet shows the parameter's title as a placeholder (#49). The query never
answers nil (an empty placeholder entity before the app wrote its options),
and the intent reads each value through `valueState` where it exists, so an
unset value never traps.

`entities(for:)` answers every id it is asked (#277): an unknown one (an
option gone since, the empty placeholder) gets an entity of that id, titled
like the default option, which the provider reads as « the default ». Left
out, the required parameter would be missing and WidgetKit would never ask
for a timeline.
"""
import json
import re
import sys

ACCESSORY = {"accessoryCircular", "accessoryRectangular", "accessoryInline"}

widgets = json.load(open(sys.argv[1]))
platform = sys.argv[2]

def swift_str(s):
    return json.dumps(s, ensure_ascii=False)

def ident(s):
    return re.sub(r"\W", "_", s)

def configurable(w, name, kind, fams):
    """The intent, entities and queries of a kind with parameters."""
    intent = "PrismIntent_" + ident(w["kind"])
    lines = []
    props = []
    for i, p in enumerate(w["parameters"]):
        entity = f"PrismEntity_{ident(w['kind'])}_{i}"
        query = f"PrismQuery_{ident(w['kind'])}_{i}"
        pid = swift_str(p["id"])
        make = f"{{ {entity}(id: $0.id, title: $0.title) }}"
        lines += [
            f"struct {entity}: AppEntity {{",
            f"    static var typeDisplayRepresentation: TypeDisplayRepresentation = {swift_str(p['title'])}",
            f"    static var defaultQuery = {query}()",
            "    let id: String",
            "    let title: String",
            '    var displayRepresentation: DisplayRepresentation { DisplayRepresentation(title: "\\(title)") }',
            "}",
            "",
            f"struct {query}: EntityQuery {{",
            f"    func entities(for identifiers: [String]) async throws -> [{entity}] {{",
            f"        prismResolve({kind}, {pid}, identifiers, placeholder: {swift_str(p['title'])}).map {make}",
            "    }",
            f"    func suggestedEntities() async throws -> [{entity}] {{",
            f"        prismOptions({kind}, {pid}).map {make}",
            "    }",
            f"    func defaultResult() async -> {entity}? {{",
            f"        prismDefaultOption({kind}, {pid}).map {make} ?? {entity}(id: \"\", title: {swift_str(p['title'])})",
            "    }",
            "}",
            "",
        ]
        props.append((f"p{i}", entity, p))
    lines += [
        f"struct {intent}: PrismConfigurationIntent {{",
        f"    static var title: LocalizedStringResource = {swift_str(w['name'])}",
    ]
    if w.get("description"):
        lines.append(f"    static var description = IntentDescription({swift_str(w['description'])})")
    lines.append(f"    static var prismKind: String {{ {kind} }}")
    for prop, entity, p in props:
        lines.append(f"    @Parameter(title: {swift_str(p['title'])}) var {prop}: {entity}")
    lines += ["    var prismValues: [String: String] {", "        var v: [String: String] = [:]"]
    for prop, _, p in props:
        lines.append(f"        if let e = prismValue(${prop}), !e.id.isEmpty {{ v[{swift_str(p['id'])}] = e.id }}")
    lines += ["        return v", "    }", "}", ""]
    lines += [
        f"struct {name}: Widget {{",
        "    var body: some WidgetConfiguration {",
        f"        AppIntentConfiguration(kind: {kind}, intent: {intent}.self, provider: PrismIntentProvider<{intent}>()) {{ PrismWidgetView(entry: $0) }}",
        f"            .configurationDisplayName({swift_str(w['name'])})",
        f"            .description({swift_str(w['description'])})",
        f"            .supportedFamilies([{fams}])",
        "    }",
        "}",
        "",
    ]
    return lines

out = ["// Generated by prism-apple-build/apple/generate_widgets.py. Do not edit.",
       "import AppIntents", "import SwiftUI", "import WidgetKit", ""]
names = []
for w in widgets:
    name = "PrismWidget_" + ident(w["kind"])
    names.append(name)
    families = [f for f in w["families"] if platform == "ios" or f not in ACCESSORY]
    if platform == "macos":
        families = [f for f in families if f != "systemExtraLarge"] or ["systemSmall"]
    fams = ", ".join("." + f for f in families) or ".systemSmall"
    kind = swift_str(w["kind"])
    if w.get("parameters"):
        out += configurable(w, name, kind, fams)
        continue
    out += [
        f"struct {name}: Widget {{",
        "    var body: some WidgetConfiguration {",
        f"        StaticConfiguration(kind: {kind}, provider: PrismProvider(kind: {kind})) {{ PrismWidgetView(entry: $0) }}",
        f"            .configurationDisplayName({swift_str(w['name'])})",
        f"            .description({swift_str(w['description'])})",
        f"            .supportedFamilies([{fams}])",
        "    }",
        "}",
        "",
    ]
out += ["@main", "struct PrismWidgetBundle: WidgetBundle {", "    var body: some Widget {"]
out += [f"        {n}()" for n in names]
if platform == "ios":
    out.append("        PrismLiveActivity()")
if not names and platform != "ios":
    out.append("        EmptyWidget()")
out += ["    }", "}"]
# Bytes, not text: Windows' text mode would write CRLF line endings and its
# ANSI code page instead of UTF-8.
sys.stdout.buffer.write(("\n".join(out) + "\n").encode("utf-8"))
