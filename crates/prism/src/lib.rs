use std::sync::Arc;

/// Includes the typed translation functions generated by
/// `prism_build::translations("locales")` in `build.rs`:
///
/// ```ignore
/// mod strings { prism::include_strings!(); }
/// text(strings::home_title(cx, &name))
/// ```
#[macro_export]
macro_rules! include_strings {
    () => {
        include!(concat!(env!("OUT_DIR"), "/prism_strings.rs"));
    };
}

/// Android entry point. Android loads apps as a library (`cdylib`), so the
/// app's code lives in `lib.rs` and this macro exports the function the Java
/// host calls first:
///
/// ```ignore
/// // lib.rs
/// pub fn run() { prism::Application::new().run(|cx| cx.new_entity(|_| Home)) }
/// prism::android_main!(run);
/// // main.rs (every other platform)
/// fn main() { my_app::run() }
/// ```
#[macro_export]
macro_rules! android_main {
    ($run:path) => {
        #[cfg(target_os = "android")]
        #[unsafe(no_mangle)]
        pub extern "system" fn Java_dev_prism_PrismHost_nativeMain(
            _env: *mut ::core::ffi::c_void,
            _class: *mut ::core::ffi::c_void,
        ) {
            $run()
        }
    };
}

