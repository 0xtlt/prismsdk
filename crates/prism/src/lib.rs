/// Entry point: configure, then [`run`](Application::run).
#[derive(Clone, Debug, Default)]
pub struct Application {
    config: AppConfig,
    #[cfg(feature = "web")]
    web: WebSetup,
    /// Smallest widths of the `Medium`, `Expanded` and `Large` size classes.
    breakpoints: Option<[f32; 3]>,
    /// The app's own locale, or the ones it supports (#229).
    locale: Option<prism_core::Locale>,
    supported_locales: Vec<prism_core::Locale>,
}

/// What [`Application::web`] does to the web app.
#[cfg(feature = "web")]
#[derive(Clone, Default)]
struct WebSetup(Option<Arc<dyn Fn(prism_web::WebApp) -> prism_web::WebApp + Send + Sync>>);

#[cfg(feature = "web")]
impl std::fmt::Debug for WebSetup {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(if self.0.is_some() {
            "WebSetup(..)"
        } else {
            "WebSetup(None)"
        })
    }
}

#[cfg(feature = "web")]
impl WebSetup {
    fn apply(&self, app: prism_web::WebApp) -> prism_web::WebApp {
        match &self.0 {
            Some(f) => f(app),
            None => app,
        }
    }
}

impl Application {
    /// An app with default settings.
    pub fn new() -> Self {
        Self::default()
    }

    /// The app's language (#229), instead of the system's or the browser's:
    /// an app written in one language says so. `<html lang>` and its
    /// direction in the first paint, Prism's own texts (« Reconnecting… »,
    /// pickers), `cx.locale()` and the app's translations follow it, on
    /// every backend. `PRISM_LOCALE` still wins; `cx.set_locale` changes it
    /// later.
    pub fn locale(mut self, tag: &str) -> Self {
        self.locale = Some(prism_core::Locale::new(tag));
        self
    }

    /// The languages the app is written in (#229): the user's (the
    /// browser's `Accept-Language`, the system's) when it is one of them,
    /// the same language in another region, else the first one.
    pub fn supported_locales<S: AsRef<str>>(mut self, tags: impl IntoIterator<Item = S>) -> Self {
        self.supported_locales = tags
            .into_iter()
            .map(|t| prism_core::Locale::new(t.as_ref()))
            .collect();
        self
    }

    /// Window title (native) or page `<title>` (web).
    pub fn title(mut self, title: impl Into<String>) -> Self {
        self.config.title = title.into();
        self
    }

    /// Initial window size in points (desktop only).
    pub fn size(mut self, width: f32, height: f32) -> Self {
        self.config.width = width;
        self.config.height = height;
        self
    }

    /// The desktop window's frame (macOS; ignored elsewhere). The default,
    /// [`WindowChrome::Standard`], keeps the system's title bar;
    /// [`WindowChrome::Custom`] removes it so the content fills the window
    /// from its top edge, the traffic lights drawn over it where
    /// `traffic_lights` says. Mark the app's own title bar with
    /// `.window_drag()` so it moves the window, and leave room for the
    /// buttons with `cx.window_controls()`. The [`title`](Self::title)
    /// still names the window (Mission Control, the Window menu, VoiceOver).
    ///
    /// ```ignore
    /// Application::new()
    ///     .title("Notes")
    ///     .window_chrome(WindowChrome::Custom { traffic_lights: Some(Point::new(16., 13.)) })
    ///     .run(|cx| cx.new_entity(|_| Notes::default()));
    /// ```
    pub fn window_chrome(mut self, chrome: WindowChrome) -> Self {
        self.config.window_chrome = chrome;
        self
    }

    /// Directory of app assets (images…) for `picture("name.png")`.
    pub fn assets(mut self, dir: impl Into<String>) -> Self {
        self.config.assets = Some(dir.into());
        self
    }

    /// App assets compiled into the binary, for an app shipped as one file
    /// (a web server in a scratch container): `picture("logo.png")` and the
    /// fonts of `fonts/` find them before the [`assets`](Self::assets)
    /// directory's files. Served hashed and immutable on the web, read from
    /// memory on macOS, iOS and Linux; Android and watchOS read the bundle's
    /// assets folder only.
    ///
    /// ```ignore
    /// Application::new()
    ///     .embedded_assets(
    ///         EmbeddedAssets::new()
    ///             .file("logo.png", include_bytes!("../assets/logo.png"))
    ///             .file("fonts/Inter.woff2", include_bytes!("../assets/fonts/Inter.woff2")),
    ///     )
    ///     .run(|cx| cx.new_entity(Home::new));
    ///
    /// // rust-embed: `#[derive(RustEmbed)] #[folder = "assets"] struct Files;`
    /// let files: EmbeddedAssets = Files::iter()
    ///     .filter_map(|name| Some((name.to_string(), Files::get(&name)?.data)))
    ///     .collect();
    /// ```
    pub fn embedded_assets(mut self, assets: EmbeddedAssets) -> Self {
        self.config.embedded_assets.merge(&assets);
        self
    }

    /// Moves the size classes: the smallest widths of `Medium`, `Expanded`
    /// and `Large`, in points (default `[600., 1024., 1440.]`). `.md()`,
    /// `.lg()`, `.xl()` and `cx.breakpoint()` follow them, and every
    /// window re-renders when it crosses one. Any other width:
    /// `.at_width(768., |s| …)`.
    pub fn breakpoints(mut self, widths: [f32; 3]) -> Self {
        self.breakpoints = Some(widths);
        self
    }

    /// Web server port (default 3000, `PRISM_PORT` overrides).
    pub fn port(mut self, port: u16) -> Self {
        self.config.port = port;
        self
    }

    /// Configures the web app (`web` feature): additions to the page's
    /// `<head>` (favicon, fonts, metas, a stylesheet), socket origins,
    /// session limits… Applied by [`run`](Self::run) and
    /// [`web_app`](Self::web_app); natively there is no web app.
    ///
    /// ```ignore
    /// Application::new()
    ///     .web(|w| w.favicon("icon.png").theme_color("#0a84ff").body_background("#101418"))
    ///     .run(|cx| cx.new_entity(Home::new));
    /// ```
    #[cfg(feature = "web")]
    pub fn web(
        mut self,
        setup: impl Fn(prism_web::WebApp) -> prism_web::WebApp + Send + Sync + 'static,
    ) -> Self {
        self.web = WebSetup(Some(Arc::new(setup)));
        self
    }

    /// The app as a web rendering service, to mount in your own server
    /// instead of [`run`](Self::run) (`web` feature):
    ///
    /// ```ignore
    /// let prism = Application::new().title("Shop").assets("assets").web_app(|cx| cx.new_entity(Home::new));
    /// let app = axum::Router::new()
    ///     .route("/api/orders", get(orders))
    ///     .merge(prism.router());   // or .nest("/app", prism.base_path("/app").router())
    /// ```
    #[cfg(feature = "web")]
    pub fn web_app<V: Render>(
        self,
        init: impl Fn(&mut App) -> Entity<V> + Send + Sync + 'static,
    ) -> prism_web::WebApp {
        let breakpoints = self.breakpoints;
        let (locale, supported) = (self.locale.clone(), self.supported_locales.clone());
        let init: AppInit = Arc::new(move |app: &mut App| {
            if let Some(b) = breakpoints {
                app.set_breakpoints(b);
            }
            app.apply_app_locale(locale.as_ref(), &supported);
            let root = init(app);
            app.set_root(root);
        });
        self.web.apply(prism_web::WebApp::new(self.config, init))
    }

    /// Starts the backend selected at compile time. `init` creates the root
    /// entity; it runs once per window, or once per browser session on the web.
    pub fn run<V: Render>(self, init: impl Fn(&mut App) -> Entity<V> + Send + Sync + 'static) {
        let breakpoints = self.breakpoints;
        let (locale, supported) = (self.locale.clone(), self.supported_locales.clone());
        let init: AppInit = Arc::new(move |app: &mut App| {
            if let Some(b) = breakpoints {
                app.set_breakpoints(b);
            }
            app.apply_app_locale(locale.as_ref(), &supported);
            let root = init(app);
            app.set_root(root);
        });
        let config = self.config;

        // Build tooling: `PRISM_DESCRIBE=<question>` prints what the bundlers
        // need (see `describe`) and exits without starting a backend.
        if let Some(question) = std::env::var("PRISM_DESCRIBE")
            .ok()
            .filter(|q| !q.is_empty())
        {
            if let Some(answer) = describe(&question, &config, &init) {
                println!("{answer}");
                return;
            }
            // An unknown question must not start the app: the bundler would
            // wait on its window.
            eprintln!(
                "prism: unknown PRISM_DESCRIBE={question} (expected one of {})",
                DESCRIBE_QUESTIONS.join(", ")
            );
            std::process::exit(2);
        }

        #[cfg(feature = "web")]
        {
            prism_web::run_app(self.web.apply(prism_web::WebApp::new(config, init)));
        }
        #[cfg(all(not(feature = "web"), feature = "native", target_os = "macos"))]
        {
            prism_macos::run(config, init);
        }
        #[cfg(all(
            not(feature = "web"),
            feature = "native",
            any(target_os = "ios", target_os = "tvos", target_os = "visionos")
        ))]
        {
            prism_ios::run(config, init);
        }
        #[cfg(all(not(feature = "web"), feature = "native", target_os = "watchos"))]
        {
            prism_watchos::run(config, init);
        }
        #[cfg(all(not(feature = "web"), feature = "native", target_os = "linux"))]
        {
            prism_linux::run(config, init);
        }
        #[cfg(all(not(feature = "web"), feature = "native", target_os = "android"))]
        {
            prism_android::run(config, init);
        }
        #[cfg(not(any(
            feature = "web",
            all(
                feature = "native",
                any(
                    target_os = "macos",
                    target_os = "ios",
                    target_os = "tvos",
                    target_os = "visionos",
                    target_os = "watchos",
                    target_os = "linux",
                    target_os = "android"
                )
            )
        )))]
        {
            let _ = (config, init);
            panic!(
                "prism: no backend for this target. Enable `web`, or build `native` for macOS/iOS."
            );
        }
    }
}

/// The questions `PRISM_DESCRIBE` answers.
const DESCRIBE_QUESTIONS: [&str; 7] = [
    "all",
    "assets",
    "widgets",
    "background",
    "live_activities",
    "widget_actions",
    "car",
];

/// The answer to `PRISM_DESCRIBE=<question>`, `None` for an unknown one.
///
/// The bundlers (`prism build|run`) ask a host build of the app what it
/// declares at startup before they bundle it for a device: its assets
/// directory, widgets (the WidgetKit extension, Android receivers),
/// background tasks (`BGTaskScheduler` identifiers), Live Activities, widget
/// buttons (App Intents) and car screen (CarPlay, Android Auto). `all`
/// answers everything in one JSON object, so the app's `init` runs once.
fn describe(question: &str, config: &AppConfig, init: &AppInit) -> Option<String> {
    let assets = || config.assets.clone().unwrap_or_default();
    if question == "assets" {
        return Some(assets());
    }
    if !DESCRIBE_QUESTIONS.contains(&question) {
        return None;
    }
    let app = Runtime::new(init).app;
    let flag = |on: bool| u8::from(on).to_string();
    Some(match question {
        "widgets" => app.describe_widgets(),
        "background" => app.describe_background(),
        "live_activities" => flag(app.uses_live_activities()),
        "widget_actions" => flag(app.handles_widget_actions()),
        "car" => flag(app.has_car()),
        _ => {
            let parse =
                |json: String| serde_json::from_str::<serde_json::Value>(&json).unwrap_or_default();
            serde_json::json!({
                "assets": assets(),
                "widgets": parse(app.describe_widgets()),
                "background": parse(app.describe_background()),
                "live_activities": app.uses_live_activities(),
                "widget_actions": app.handles_widget_actions(),
                "car": app.has_car(),
            })
            .to_string()
        }
    })
}

